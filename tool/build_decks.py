"""Builds src/game/moreDecks.ts from the plain-text deck files in decks/.

Run from the repo root:  python tool/build_decks.py

Each deck in decks/*.txt is two lines followed by a blank line:

    id|Name|emoji|BADGE|How to give clues for this deck.
    Word one, Word two, Word three, ...

BADGE is empty, NEW or POPULAR. Words are comma-separated, so a word must
not contain a comma. Poster colours are assigned from PALETTE in order.
"""

import glob
import json
import sys

# Poster gradients (top, bottom); the bottom colour doubles as the panel.
PALETTE = [
    ("#FF8A65", "#D84315"),
    ("#4DD0E1", "#00838F"),
    ("#BA68C8", "#6A1B9A"),
    ("#AED581", "#558B2F"),
    ("#FFD54F", "#F57F17"),
    ("#64B5F6", "#1565C0"),
    ("#F06292", "#AD1457"),
    ("#4DB6AC", "#00695C"),
    ("#9575CD", "#4527A0"),
    ("#FFB74D", "#E65100"),
    ("#E57373", "#B71C1C"),
    ("#7986CB", "#283593"),
]

BADGES = {"", "NEW", "POPULAR"}


def parse(path):
    decks = []
    blocks = [b for b in open(path, encoding="utf-8").read().split("\n\n") if b.strip()]
    for block in blocks:
        lines = [l for l in block.strip().splitlines() if l.strip()]
        if len(lines) != 2:
            sys.exit(f"{path}: expected 2 lines per deck, got {len(lines)}:\n{block}")
        head = lines[0].split("|")
        if len(head) != 5:
            sys.exit(f"{path}: bad header: {lines[0]}")
        did, name, emoji, badge, blurb = (h.strip() for h in head)
        if badge not in BADGES:
            sys.exit(f"{path}: unknown badge {badge!r} in {did}")
        words = [w.strip() for w in lines[1].split(",") if w.strip()]
        lower = [w.lower() for w in words]
        dupes = {w for w in lower if lower.count(w) > 1}
        if dupes:
            sys.exit(f"{path}: {did} has duplicate words: {sorted(dupes)}")
        if len(words) < 20:
            sys.exit(f"{path}: {did} has only {len(words)} words")
        decks.append(dict(id=did, name=name, emoji=emoji, badge=badge, blurb=blurb, words=words))
    return decks


def main():
    decks = []
    for path in sorted(glob.glob("decks/*.txt")):
        decks.extend(parse(path))
    ids = [d["id"] for d in decks]
    if len(ids) != len(set(ids)):
        sys.exit("duplicate deck ids")

    out = [
        "// Generated by tool/build_decks.py from decks/*.txt. Edit those, not this file.",
        "import type { Deck } from './types';",
        "",
        "export const moreDecks: Deck[] = [",
    ]
    for i, d in enumerate(decks):
        top, bottom = PALETTE[i % len(PALETTE)]
        out.append("  {")
        out.append(f"    id: {json.dumps(d['id'])},")
        out.append(f"    name: {json.dumps(d['name'], ensure_ascii=False)},")
        out.append(f"    emoji: {json.dumps(d['emoji'], ensure_ascii=False)},")
        out.append(f"    colors: [{json.dumps(top)}, {json.dumps(bottom)}],")
        out.append(f"    panel: {json.dumps(bottom)},")
        out.append("    ink: '#FFFFFF',")
        if d["badge"]:
            out.append(f"    badge: {json.dumps(d['badge'])},")
        out.append(f"    blurb: {json.dumps(d['blurb'], ensure_ascii=False)},")
        out.append("    words: [")
        line = ""
        for w in d["words"]:
            item = json.dumps(w, ensure_ascii=False) + ","
            if line and len(line) + 1 + len(item) > 90:
                out.append(f"      {line}")
                line = item
            else:
                line = f"{line} {item}" if line else item
        out.append(f"      {line}")
        out.append("    ],")
        out.append("  },")
    out.append("];")
    open("src/game/moreDecks.ts", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"Wrote {len(decks)} decks, {sum(len(d['words']) for d in decks)} words.")


if __name__ == "__main__":
    main()
